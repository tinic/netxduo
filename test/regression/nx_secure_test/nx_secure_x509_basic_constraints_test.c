static ULONG error_counter;

static VOID check(UINT condition)
{
    if (!condition)
    {
        error_counter++;
    }
}

static VOID remote_add(NX_SECURE_X509_CERT *cert, const UCHAR *der, UINT der_len, CHAR *buf1, UINT buf1_size, CHAR *buf2, UINT buf2_size)
{
    check(_nx_secure_x509_certificate_initialize(cert, (UCHAR *)der, (USHORT)der_len, NX_NULL, 0, NX_NULL, 0, NX_SECURE_X509_KEY_TYPE_NONE) == NX_SUCCESS);
    check(_nx_secure_x509_certificate_list_add(&session.nx_secure_tls_credentials.nx_secure_tls_certificate_store.nx_secure_x509_remote_certificates,
                                               cert, NX_TRUE) == NX_SUCCESS);
    cert -> nx_secure_x509_public_cipher_metadata_area = buf1;
    cert -> nx_secure_x509_public_cipher_metadata_size = buf1_size;
    cert -> nx_secure_x509_hash_metadata_area = buf2;
    cert -> nx_secure_x509_hash_metadata_size = buf2_size;
    cert -> nx_secure_x509_cipher_table = session.nx_secure_tls_crypto_table -> nx_secure_tls_x509_cipher_table;
    cert -> nx_secure_x509_cipher_table_size = session.nx_secure_tls_crypto_table -> nx_secure_tls_x509_cipher_table_size;
}

/* A fresh session whose trusted store holds root; ica (if any) and leaf as a
   received chain; the verdict on leaf.  */
static UINT chain_verify(const UCHAR *root_der, UINT root_len, const UCHAR *ica_der, UINT ica_len,
                         const UCHAR *leaf_der, UINT leaf_len)
{
UINT status;

    memset(&session, 0, sizeof(session));
    check(nx_secure_tls_session_create(&session, &nx_crypto_tls_ciphers_ecc, crypto_metadata, sizeof(crypto_metadata)) == NX_SUCCESS);
    check(nx_secure_tls_ecc_initialize(&session, nx_crypto_ecc_supported_groups, nx_crypto_ecc_supported_groups_size,
                                       nx_crypto_ecc_curves) == NX_SUCCESS);
    check(_nx_secure_tls_session_packet_buffer_set(&session, packet_buffer, sizeof(packet_buffer)) == NX_SUCCESS);

    memset(&root_cert, 0, sizeof(root_cert));
    memset(&ica_cert, 0, sizeof(ica_cert));
    memset(&leaf_cert, 0, sizeof(leaf_cert));
    check(_nx_secure_x509_certificate_initialize(&root_cert, (UCHAR *)root_der, (USHORT)root_len, NX_NULL, 0, NX_NULL, 0, NX_SECURE_X509_KEY_TYPE_NONE) == NX_SUCCESS);
    check(_nx_secure_tls_trusted_certificate_add(&session, &root_cert) == NX_SUCCESS);
    if (ica_der)
    {
        remote_add(&ica_cert, ica_der, ica_len, ica_buf1, sizeof(ica_buf1), ica_buf2, sizeof(ica_buf2));
    }
    remote_add(&leaf_cert, leaf_der, leaf_len, leaf_buf1, sizeof(leaf_buf1), leaf_buf2, sizeof(leaf_buf2));

    status = _nx_secure_x509_certificate_chain_verify(&session.nx_secure_tls_credentials.nx_secure_tls_certificate_store, &leaf_cert, 0);
    nx_secure_tls_session_delete(&session);
    return(status);
}

static void    thread_0_entry(ULONG thread_input)
{

    NX_PARAMETER_NOT_USED(thread_input);
    printf("NetX Secure Test:   X509 Basic Constraints Test.......................");

    nx_secure_tls_initialize();

    check(chain_verify(ECCA4_der, ECCA4_der_len, ECIntm_der, ECIntm_der_len, ECRevoked2_der, ECRevoked2_der_len) == NX_SUCCESS);
    check(chain_verify(ECCA4_der, ECCA4_der_len, ECIntm_not_ca_der, ECIntm_not_ca_der_len, ECRevoked2_der, ECRevoked2_der_len) ==
          NX_SECURE_X509_INVALID_CA_CERTIFICATE);
    check(chain_verify(ECCA2_der, ECCA2_der_len, NX_NULL, 0, ECTestServer2_der, ECTestServer2_der_len) == NX_SUCCESS);
    check(chain_verify(ECCA2_v1_der, ECCA2_v1_der_len, NX_NULL, 0, ECTestServer2_der, ECTestServer2_der_len) ==
          NX_SECURE_X509_INVALID_CA_CERTIFICATE);

    if (error_counter)
    {
        printf("ERROR!\n");
        test_control_return(1);
    }
    printf("SUCCESS!\n");
    test_control_return(0);
}

